import re

# letters (4-8, non-greedy) + digit block starting with 5 (sem V) or 6 (sem VI)
# (tolerate OCR letter-O inside digits; support 5P0x/6P0x practical codes)
_CODE_RE = re.compile(r"([A-Z]{4,8}?)([56][0-9OP]{3,4})\b")

_TYPE_NAME = {"MJ": "MJ", "MO": "MO", "NO": "NO", "XO": "XO",
              "VO": "VOC", "VA": "VAC"}


def _parse(raw):
    seen, out = set(), []
    text = raw.upper().replace("Ǫ", "O")          # OCR fix: Ǫ -> O
    for m in _CODE_RE.finditer(text):
        letters, tail = m.group(1), m.group(2)
        tail = tail.replace("O", "0")             # OCR fix: 6PO7 -> 6P07
        cat = _TYPE_NAME.get(letters[-2:])
        if not cat:
            continue
        sem = "V" if tail.startswith("5") else "VI"
        code = letters + tail
        if code not in seen:
            seen.add(code)
            out.append((code, cat, sem))
    return out


